const WARN = '⚠️ Важно про группу: отчёт в группе видят ВСЕ её участники. Подключай группу, только если ' +
  'там сидит закрытая команда заказчика. Есть посторонние — лучше личный чат.'

function StepBlock({ icon, title, steps }) {
  return (
    <div className="a-guide-block">
      <div className="a-guide-block-title">{icon} {title}</div>
      <ol className="a-guide-steps">
        {steps.map((s, i) => <li key={i}>{s}</li>)}
      </ol>
    </div>
  )
}

export function MessengerGuide({ scenarios = ['dm'], channels = ['telegram', 'max'] }) {
  const CH = { telegram: ['✈️', 'Telegram'], max: ['🟦', 'MAX'] }
  return (
    <details className="a-guide">
      <summary>📖 Инструкция: как подключить (пошагово)</summary>
      <div className="a-guide-body">
        {scenarios.includes('dm') && (
          <>
            <div className="a-guide-h">👤 Личный чат человека</div>
            {channels.map((ch) => (
              <StepBlock key={ch} icon={CH[ch][0]} title={CH[ch][1]} steps={DM_STEPS[ch]} />
            ))}
          </>
        )}
        {scenarios.includes('group') && (
          <>
            <div className="a-guide-h">👥 Группа заказчика</div>
            {channels.map((ch) => (
              <StepBlock key={ch} icon={CH[ch][0]} title={CH[ch][1]} steps={GROUP_STEPS[ch]} />
            ))}
            <div className="a-guide-warn">{WARN}</div>
          </>
        )}
      </div>
    </details>
  )
}
